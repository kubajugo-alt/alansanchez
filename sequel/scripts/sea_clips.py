#!/usr/bin/env python3
"""The sea that moves (2026-10-30): a Higgsfield (kling3_0) loop of a room's painting, start and end on the painting,
in which only the water moves, cut down to where it moves.

  python3 scripts/sea_clips.py <room> <video.mp4> [<room> <video.mp4> ...]

For each: the motion over the whole loop (per-pixel spread of the frames) thresholded, closed and grown into a mask;
its bounding box cropped out of the video (scaled to the 1280x720 painting, the slight darkening of the model's frames
lifted back) to art/video/<room>.mp4 (h264, no sound) and .webm (VP9) and the mask, feathered, to art/video/<room>_mask.png.
art/video/clips.json and js/story/sea_clips.js (S.SEA, read by js/story/sea.js) get {room: [x, y, w, h]}, where
the clip sits on the painting.
"""
import json, os, subprocess, sys
import numpy as np, cv2

SEQ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(SEQ, 'art/video')
# where the water is, for rooms where something else stirs in the loop (x0, y0, x1, y1 on the 1280x720 painting): the
# phone box's glass and a palm frond on the promenade, a palm at the top left of the sunny beach
ROI = {'canteras': (415, 330, 1010, 520), 'beach_sun': (0, 300, 1280, 520),
       'hotel_lobby': (0, 0, 236, 500), 'hotel_lobby_day': (0, 0, 236, 500)}   # (the lobby: only its street windows; its night loop
# came back all but still, so the night lobby keeps its canvas ripple and has no clip)


def frames(path, w, h, fps=8):
    raw = subprocess.run(['ffmpeg', '-v', 'error', '-i', path, '-vf', f'fps={fps},scale={w}:{h}', '-f', 'rawvideo',
                          '-pix_fmt', 'rgb24', '-'], capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.uint8).reshape(-1, h, w, 3).astype(np.float32)


def clip(room, src):
    a = frames(src, 640, 360)
    spread = a.std(0).mean(2)
    m = (cv2.GaussianBlur(spread, (0, 0), 2) > 2.2).astype(np.uint8)
    m = cv2.morphologyEx(m, cv2.MORPH_CLOSE, np.ones((9, 9), np.uint8))
    n, lab, st, _ = cv2.connectedComponentsWithStats(m)
    keep = np.zeros_like(m)
    for i in range(1, n):
        if st[i, cv2.CC_STAT_AREA] >= 60: keep[lab == i] = 1   # (specks: compression noise, not the sea)
    if room in ROI:
        x0, y0, x1, y1 = (v // 2 for v in ROI[room]); roi = np.zeros_like(keep); roi[y0:y1, x0:x1] = 1; keep *= roi
    keep = cv2.dilate(keep, np.ones((7, 7), np.uint8))
    ys, xs = np.nonzero(keep)
    x0, y0, x1, y1 = xs.min() * 2, ys.min() * 2, xs.max() * 2 + 2, ys.max() * 2 + 2
    x0, y0 = max(0, x0 - 8) // 2 * 2, max(0, y0 - 8) // 2 * 2
    x1, y1 = min(1280, x1 + 8) // 2 * 2, min(720, y1 + 8) // 2 * 2
    w, h = x1 - x0, y1 - y0
    full = cv2.resize(keep * 255, (1280, 720), interpolation=cv2.INTER_LINEAR)
    alpha = cv2.GaussianBlur(full.astype(np.float32), (0, 0), 6)[y0:y1, x0:x1]
    rgba = np.zeros((h, w, 4), np.uint8); rgba[..., 3] = np.clip(alpha, 0, 255)
    cv2.imwrite(os.path.join(OUT, room + '_mask.png'), rgba)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', src, '-an', '-vf',
                    f'scale=1280:720,crop={w}:{h}:{x0}:{y0},lutrgb=r=val+3:g=val+2:b=val+2,format=yuv420p',
                    '-c:v', 'libx264', '-preset', 'slow', '-crf', '24', '-movflags', '+faststart',
                    os.path.join(OUT, room + '.mp4')], check=True)
    # (and VP9 for browsers without H.264, e.g. Chromium builds without the proprietary codecs)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', os.path.join(OUT, room + '.mp4'), '-an', '-c:v', 'libvpx-vp9', '-b:v', '0',
                    '-crf', '36', '-row-mt', '1', os.path.join(OUT, room + '.webm')], check=True)
    return [int(v) for v in (x0, y0, w, h)]


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    idx = os.path.join(OUT, 'clips.json')
    clips = json.load(open(idx)) if os.path.exists(idx) else {}
    args = sys.argv[1:]
    for room, src in zip(args[::2], args[1::2]):
        clips[room] = clip(room, src); print(room, clips[room], os.path.getsize(os.path.join(OUT, room + '.mp4')) // 1024, 'KB')
    json.dump(clips, open(idx, 'w'), indent=1, sort_keys=True)
    with open(os.path.join(SEQ, 'js/story/sea_clips.js'), 'w') as f:
        f.write('// Generated by sequel/scripts/sea_clips.py: where each painting\'s sea loop sits on it, [x, y, w, h] on the\n'
                '// 1280x720 painting (art/video/<bg>.mp4 and <bg>_mask.png). Do not edit by hand.\n'
                'window.S.SEA = ' + json.dumps(clips, sort_keys=True) + ';\n')
