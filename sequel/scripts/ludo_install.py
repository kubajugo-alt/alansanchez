#!/usr/bin/env python3
"""The approved Ludo runs (the user, 2026-10-28: "all good, put them all in the game") written into the game.

  python3 sequel/scripts/ludo_install.py

For every run in scripts/ludo_runs.json: its fitted frames (scripts/ludo_fit.py: art/review/ludo/<run>/fit/fNN.webp)
are copied to art/sprites/<run>_NN.webp, and js/sprites_ludo.js gets their sprite data (one box per run, so nothing
in a run slides or jumps; facesLeft carried from the painting the run started from) and window.LUDO: per run its
frames, frame rate, and what the engine needs (scripts/ludo_measure.py): a walk's ground per frame, an action's peak
frame (where the pose holds while the story runs). js/story/core.js builds the cast's frames from window.LUDO.
"""
import glob, json, os, re, shutil, subprocess, sys

SEQ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(SEQ, 'scripts'))
import ludo_measure, head_scale
from PIL import Image

L = os.path.join(SEQ, 'art/review/ludo')
SPR = os.path.join(SEQ, 'art/sprites')
# measured by eye where the feet test misreads (scripts/ludo_measure.py): Vasco's side walk is two steps a loop
FIX = {'vasco_walk_side': {'steps': 2, 'step': 0.0162}}
TALK = {'vasco': 'vasco_talk_a', 'baute': 'talk_baute', 'yeray': 'talk_yeray'}  # where each scaled head is measured
REF = {}


def canva_meta():
    js = subprocess.run(['node', '-e', "global.window={};require(process.argv[1]);console.log(JSON.stringify(window.SPRITES))",
                         os.path.join(SEQ, 'js/sprites_canva.js')], capture_output=True, text=True, check=True).stdout
    return json.loads(js)


if __name__ == '__main__':
    runs = json.load(open(os.path.join(SEQ, 'scripts/ludo_runs.json')))['runs']
    src = canva_meta()
    meas = {}
    for r in runs:
        n = r['name']
        if '_walk_' in n: meas[n] = FIX.get(n) or ludo_measure.walk(n, '_walk_side' in n)
        elif not n.startswith('talk_') and '_talk_' not in n and '_turn_' not in n: meas[n] = ludo_measure.action(n)
    sprites, ludo = {}, {}
    for r in runs:
        n = r['name']; fit = json.load(open(os.path.join(L, n, 'fit.json'))); m = fit['meta']
        fl = bool((src.get(r['a']) or {}).get('facesLeft'))
        keys = []
        files = sorted(glob.glob(os.path.join(L, n, 'fit', 'f*.webp')))
        who, k = head_scale.scale_for(n)
        if who:   # a larger head (scripts/head_scale.py): the frames get headroom on top, so the box grows by PAD
            ims = [Image.open(f).convert('RGBA') for f in files]
            ref = REF.get(who) or REF.setdefault(who, head_scale.ref_of(Image.open(os.path.join(L, TALK[who], 'fit', 'f00.webp')).convert('RGBA')))
            boxes = head_scale.heads_of(ims, ref)
            P = head_scale.PAD
            m = dict(m, hh=m['hh'] + P, fy=round(m['fy'] + P, 1), top=round(m['top'] + P, 1))
        for i, f in enumerate(files):
            key = f'{n}_{i:02d}'; keys.append(key)
            if who: head_scale.grow(ims[i], boxes[i], k, head_scale.PAD).save(os.path.join(SPR, key + '.webp'), 'WEBP', quality=90, method=6)
            else: shutil.copyfile(f, os.path.join(SPR, key + '.webp'))
            sprites[key] = dict(m, **({'facesLeft': True} if fl else {}))
        ludo[n] = dict({'frames': keys, 'fps': fit['fps']}, **meas.get(n, {}))
    out = os.path.join(SEQ, 'js/sprites_ludo.js')
    with open(out, 'w') as f:
        f.write('// Generated by sequel/scripts/ludo_install.py: the approved Ludo runs. Do not edit by hand.\n')
        f.write('window.SPRITES = Object.assign(window.SPRITES || {}, ' + json.dumps(sprites, separators=(',', ':')) + ');\n')
        f.write('window.LUDO = ' + json.dumps(ludo, indent=1) + ';\n')
    print(len(runs), 'runs,', len(sprites), 'frames; measures:', json.dumps(meas))
