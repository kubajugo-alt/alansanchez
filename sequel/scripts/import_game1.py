#!/usr/bin/env python3
"""Copy the Game I frames the sequel borrows (Alan and Vasco, until their Ludo sets are made) into sequel/art,
and write sequel/js/sprites.js and sequel/js/faces.js for them.

Game I is read, never written. Run from anywhere:  python3 sequel/scripts/import_game1.py

The list below is everything borrowed. A frame that is in Game I's js/sprites.js is copied from art/sprites/; one that
is an approved review candidate (art/review/candidates.json + approvals.json) is copied from its src. Face kits
(art/faces/<frame>_*.webp, js/faces.js) come along so the borrowed frames blink. Placeholder figures for the new cast
(scripts/placeholders.py) are added to sprites.js by that script, not here.
"""
import json, os, re, shutil, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SEQ = os.path.dirname(HERE)            # sequel/
G1 = os.path.dirname(SEQ)              # the repository root: Game I

BORROW = {
    'alan': ['alan_side', 'alan_idle2', 'alan_talk', 'alan_talk2', 'alan_front', 'alan_back',
             'alan_front_walk1', 'alan_front_walk2', 'alan_back_walk1', 'alan_back_walk2',
             'alan_reach', 'alan_read', 'alan_pickup', 'alan_write', 'alan_phone', 'alan_fluster', 'alan_flirt',
             'alan_wink', 'alan_drink', 'alan_yawn', 'alan_stretch', 'alan_climb', 'alan_pull', 'alan_ring', 'alan_asleep',
             'alan_smoke_light', 'alan_smoke_inhale', 'alan_smoke_exhale', 'alan_smoke_hold']
            + ['alan_w24_%02d' % i for i in range(24)],
    'vasco': ['vasco', 'vasco_idle2', 'vasco_idle3', 'vasco_talk', 'vasco_talk2', 'vasco_talk3', 'vasco_front', 'vasco_back',
              'vasco_kneel', 'vasco_kneel_talk', 'vasco_kneel_look', 'vasco_trowel', 'vasco_trowel_talk', 'vasco_coffee',
              'vasco_coffee_sip', 'vasco_worried', 'vasco_stern', 'vasco_tender', 'vasco_laugh', 'vasco_find', 'vasco_give',
              'vasco_crouch', 'vasco_sit', 'vasco_hand_out', 'vasco_deflate']
             + ['vasco_walk6_p%d' % i for i in (1, 3, 5, 7, 9, 11, 13, 15)],
}


def load_js_object(path, var):
    t = open(path, encoding='utf8').read()
    i = t.index('window.%s = ' % var) + len('window.%s = ' % var)
    return json.loads(t[i:].rstrip().rstrip(';'))


def main():
    sprites = load_js_object(os.path.join(G1, 'js/sprites.js'), 'SPRITES')
    faces = load_js_object(os.path.join(G1, 'js/faces.js'), 'FACES')
    cands = {c['id']: c for c in json.load(open(os.path.join(G1, 'art/review/candidates.json')))['candidates']}
    appr = json.load(open(os.path.join(G1, 'art/review/approvals.json')))
    out_spr, out_faces, missing = {}, {}, []
    os.makedirs(os.path.join(SEQ, 'art/sprites'), exist_ok=True)
    os.makedirs(os.path.join(SEQ, 'art/faces'), exist_ok=True)
    for char, frames in BORROW.items():
        for k in frames:
            if k in sprites and os.path.exists(os.path.join(G1, 'art/sprites', k + '.webp')):
                src, meta = os.path.join(G1, 'art/sprites', k + '.webp'), dict(sprites[k])
            elif k in cands and (appr.get(k) or {}).get('decision') == 'approved':
                src, meta = os.path.join(G1, cands[k]['src']), dict(cands[k]['meta'])
            else:
                missing.append(k); continue
            meta.pop('src', None)
            shutil.copyfile(src, os.path.join(SEQ, 'art/sprites', k + '.webp'))
            out_spr[k] = meta
            if k in faces and faces[k].get('ok') is True:
                out_faces[k] = faces[k]
                for f in os.listdir(os.path.join(G1, 'art/faces')):
                    if re.match(re.escape(k) + r'_(?:[A-H](?:_\d+)?|eyes_\w+)\.webp$', f):
                        shutil.copyfile(os.path.join(G1, 'art/faces', f), os.path.join(SEQ, 'art/faces', f))
    with open(os.path.join(SEQ, 'js/sprites_game1.js'), 'w') as fh:
        fh.write('// Generated by sequel/scripts/import_game1.py: the frames borrowed from Game I (Alan, Vasco) until the\n'
                 '// sequel\'s own sets are made. Do not edit by hand.\n')
        fh.write('window.SPRITES = Object.assign(window.SPRITES || {}, ' + json.dumps(out_spr, indent=1, sort_keys=True) + ');\n')
    with open(os.path.join(SEQ, 'js/faces.js'), 'w') as fh:
        fh.write('// Generated by sequel/scripts/import_game1.py: Game I\'s approved face kits for the borrowed frames.\n')
        fh.write('window.FACES = ' + json.dumps(out_faces, indent=0, sort_keys=True) + ';\n')
    print('borrowed %d frames, %d face kits' % (len(out_spr), len(out_faces)))
    if missing:
        print('not found in Game I (skipped):', ', '.join(missing))


if __name__ == '__main__':
    sys.exit(main())
