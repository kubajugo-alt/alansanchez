#!/usr/bin/env python3
"""Cut a Canva character design (one figure on a flat green background) into a game sprite.

  python3 sequel/scripts/figure_cut.py <design name> <sprite id> [--left]

Reads art/designs/<design name>.png (sequel/scripts/canva_in.py figure ...), keys out the background colour (sampled
from the corners), keeps the largest figure, despills the green fringe, scales the figure to 720 px tall, and writes
art/sprites/<sprite id>.webp plus its metadata into js/sprites_canva.js (same fields as Game I's js/sprites.js:
w, hh, h, ax, fy, top; facesLeft with --left, for a figure painted looking left).
"""
import json, os, sys
import numpy as np
from PIL import Image, ImageFilter

SEQ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
name, sid = sys.argv[1], sys.argv[2]
left = '--left' in sys.argv
im = np.asarray(Image.open(os.path.join(SEQ, 'art/designs', name + '.png')).convert('RGB')).astype(np.float32)
H, W, _ = im.shape
corners = np.concatenate([im[:12, :12].reshape(-1, 3), im[:12, -12:].reshape(-1, 3), im[-12:, :12].reshape(-1, 3), im[-12:, -12:].reshape(-1, 3)])
bg = np.median(corners, axis=0)
d = np.sqrt(((im - bg) ** 2).sum(axis=2))
# green dominance helps on a chroma background: a pixel much greener than red and blue is background
g = im[:, :, 1] - np.maximum(im[:, :, 0], im[:, :, 2])
greenish = bg[1] > bg[0] + 40 and bg[1] > bg[2] + 40
alpha = np.clip((d - 40) / 60, 0, 1)
if greenish:
    alpha = np.minimum(alpha, np.clip((90 - g) / 60, 0, 1))
# keep the largest connected figure (drops specks and stray marks)
mask = alpha > 0.5
try:
    from scipy import ndimage
    lab, n = ndimage.label(mask)
    if n > 1:
        sizes = ndimage.sum(mask, lab, range(1, n + 1))
        keep = lab == (1 + int(np.argmax(sizes)))
        keep = ndimage.binary_dilation(keep, iterations=3)
        alpha = alpha * keep
except ImportError:
    pass
# despill: pull green down to the larger of red and blue where the figure meets the background
if greenish:
    lim = np.maximum(im[:, :, 0], im[:, :, 2])
    im[:, :, 1] = np.where(im[:, :, 1] > lim, lim + (im[:, :, 1] - lim) * 0.25, im[:, :, 1])
rgba = np.dstack([im, alpha * 255]).clip(0, 255).astype(np.uint8)
img = Image.fromarray(rgba, 'RGBA')
a = img.getchannel('A').filter(ImageFilter.GaussianBlur(0.6)); img.putalpha(a)
ys, xs = np.where(np.asarray(img.getchannel('A')) > 40)
x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
fig = img.crop((x0, y0, x1, y1))
s = 720 / fig.height
fig = fig.resize((max(1, round(fig.width * s)), 720), Image.LANCZOS)
pad = 20
canvas = Image.new('RGBA', (fig.width + 2 * pad, 720 + 2 * pad), (0, 0, 0, 0))
canvas.paste(fig, (pad, pad), fig)
# the anchor: the middle of the feet (the bottom 4% of the figure)
al = np.asarray(canvas.getchannel('A'))
foot = np.where(al[pad + int(720 * 0.96): pad + 720].max(axis=0) > 60)[0]
ax = float(foot.mean()) if len(foot) else canvas.width / 2
out = os.path.join(SEQ, 'art/sprites', sid + '.webp')
canvas.save(out, quality=92, lossless=False, alpha_quality=100)
meta = {'w': canvas.width, 'hh': canvas.height, 'h': 720.0, 'ax': round(ax, 1), 'fy': float(pad + 720), 'top': float(pad)}
if left: meta['facesLeft'] = True
mp = os.path.join(SEQ, 'js/sprites_canva.js')
data = {}
if os.path.exists(mp):
    t = open(mp).read(); data = json.loads(t[t.index('{', t.index('Object.assign')): t.rindex(')')])
data[sid] = meta
with open(mp, 'w') as f:
    f.write('// Generated by sequel/scripts/figure_cut.py: the cast designed in Canva, cut out for the game. Do not edit by hand.\n')
    f.write('window.SPRITES = Object.assign(window.SPRITES || {}, ' + json.dumps(data, indent=0, sort_keys=True) + ');\n')
print(out, meta)
