#!/usr/bin/env python3
"""The airport kiss (the user, 2026-10-31: "awesome") into the game: Ludo's improved sheet (art/review/ludo/gando_kiss/
improve/sheet.webp, 6x6 frames of 533x760, made from art/sprites/pair_gando_stand.webp: Alan's and Vasco's standing
sprites side by side) cut to art/sprites/duo_gando_kiss_NN.webp, with their metadata in art/designs/sprites.json ->
js/sprites_canva.js. Every frame shares one box, anchored on Alan's feet (his ax in the two-shot), so the run stands
exactly where he does; Vasco's anchor is DUO_GAP further right (js/story/tue.js S.kissAtGando plays it).

  python3 sequel/scripts/duo_kiss_install.py
"""
import json, os
from PIL import Image

SEQ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sheet = Image.open(os.path.join(SEQ, 'art/review/ludo/gando_kiss/improve/sheet.webp')).convert('RGBA')
w, h = sheet.size[0] // 6, sheet.size[1] // 6
side = os.path.join(SEQ, 'art/designs/sprites.json'); meta = json.load(open(side))
for i in range(36):
    f = sheet.crop(((i % 6) * w, (i // 6) * h, (i % 6 + 1) * w, (i // 6 + 1) * h))
    n = f'duo_gando_kiss_{i:02d}'
    f.save(os.path.join(SEQ, 'art/sprites', n + '.webp'), quality=92, method=6)
    # (the two-shot: Alan's sprite at 0..195, his anchor 79.5; Vasco's flipped at 281..533, his anchor 392.3)
    meta[n] = {'w': w, 'hh': 760, 'h': 720.0, 'ax': 79.5, 'fy': 740.0, 'top': 20.0, 'rigid': True}
json.dump(meta, open(side, 'w'), indent=1, sort_keys=True)
with open(os.path.join(SEQ, 'js/sprites_canva.js'), 'w') as f:
    f.write('// Generated by sequel/scripts/figure_cut.py: the cast designed in Canva, cut out for the game. Do not edit by hand.\n')
    f.write('window.SPRITES = Object.assign(window.SPRITES || {}, ' + json.dumps(meta, indent=0, sort_keys=True) + ');\n')
print('36 frames installed')
