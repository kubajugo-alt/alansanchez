#!/usr/bin/env python3
"""Install the boxes moved in the hotspot tool (HANDOFF entry 146).

  python3 sequel/scripts/spots_install.py <dir of the tool's db docs>

The tool (art/review/spots/, published as an artifact with a db) keeps one document per moved box in its `spots`
collection: {room, key, name, rect}. Export them (ArtifactData list, collection "spots", out_dir <dir>) and run this:
it writes js/story/spots.js, `S.SPOT_EDITS = {room: {key: [x, y, w, h]}}`, which layout.js applies over its own boxes
(a key is the hotspot's name, or "name#2" for the second hotspot of that name in a room). A moved box's walk-to point is
dropped, so the engine walks to the box as it does for every box layout.js sets.
"""
import glob, json, os, sys

SEQ = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
edits = {}
for f in sorted(glob.glob(os.path.join(sys.argv[1], '**', '*.json'), recursive=True)):
    d = json.load(open(f)); d = d.get('data', d)
    if not (isinstance(d, dict) and d.get('room') and d.get('key') and isinstance(d.get('rect'), list) and len(d['rect']) == 4): continue
    edits.setdefault(d['room'], {})[d['key']] = [int(round(v)) for v in d['rect']]
out = os.path.join(SEQ, 'js/story/spots.js')
with open(out, 'w') as fh:
    fh.write('// Generated by sequel/scripts/spots_install.py from the hotspot tool (art/review/spots/): the boxes the user moved,\n')
    fh.write('// by room and hotspot name ("name#2": the second of that name), [x, y, w, h] in room pixels. layout.js applies them\n')
    fh.write('// over its own. Do not edit by hand: move the box in the tool and install again.\n')
    fh.write('window.S.SPOT_EDITS = ' + json.dumps(edits, indent=1, ensure_ascii=False, sort_keys=True) + ';\n')
print(sum(len(v) for v in edits.values()), 'boxes in', len(edits), 'rooms ->', out)
