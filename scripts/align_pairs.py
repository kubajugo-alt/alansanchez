# Keep furniture still when a background extra swaps frames: register frame B onto
# frame A using only the furniture (bench, table, stool, crate) and rewrite B's
# anchors in js/sprites.js so the engine draws it in exactly the same place.
#   python3 scripts/align_pairs.py      (run after scripts/matte.py)
import os, json, re
import numpy as np, cv2
from PIL import Image
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
# pair -> fraction of the frame height (from the bottom) where the furniture is
PAIRS = {('npc_bench', 'npc_bench_b'): 0.55, ('npc_cards', 'npc_cards_b'): 0.42, ('npc_guitar', 'npc_guitar_b'): 0.4,
         ('npc_mender1', 'npc_mender1_b'): 0.32, ('npc_mender2', 'npc_mender2_b'): 0.32, ('npc_fish', 'npc_fish_b'): 0.5, ('npc_couple', 'npc_couple_b'): 0.55,
         ('npc_mender1', 'npc_mender1_talk'): 0.32, ('npc_mender2', 'npc_mender2_talk'): 0.32}
# frames painted at a different scale from the rest of their set (the cat: a walking
# cat is much taller and longer than the sleeping loaf it was sized against)
SCALE = {'ines_walk1': 1.06, 'ines_walk2': 1.06, 'alan_swim': 0.6, 'alan_swim2': 0.6, 'alan_swim_wave': 0.6, 'pessoa_walk1': 1.45, 'pessoa_walk2': 1.45, 'pessoa_jump': 1.45, 'pessoa_eat': 1.15}
# facing fixes for frames already matted (mirrors FACES_LEFT in matte.py)
FACING = {'lacerda_walkA': True, 'lacerda_walkB': True, 'tomas_sweepL': True, 'abilio': True, 'abilio_idle2': True, 'robe_terror': False}
js = os.path.join(root, 'js', 'sprites.js')
txt = open(js).read()
meta = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
def load(n):
    a = np.asarray(Image.open(os.path.join(root, 'art', 'sprites', n + '.webp')).convert('RGBA'))
    return cv2.cvtColor(a[..., :3], cv2.COLOR_RGB2GRAY), a[..., 3]
orb = cv2.ORB_create(4000)
for (A, B), frac in PAIRS.items():
    if A not in meta or B not in meta: continue
    ga, ma = load(A); gb, mb = load(B)
    best = None
    for f in sorted({frac, frac * 0.6, frac * 0.8, frac * 1.2}):
        ra = np.zeros_like(ma); ra[int(ma.shape[0] * (1 - f)):] = 255; ra &= (ma > 128).astype(np.uint8) * 255
        rb = np.zeros_like(mb); rb[int(mb.shape[0] * (1 - f)):] = 255; rb &= (mb > 128).astype(np.uint8) * 255
        ka, da = orb.detectAndCompute(ga, ra); kb, db = orb.detectAndCompute(gb, rb)
        if da is None or db is None: continue
        m = sorted(cv2.BFMatcher(cv2.NORM_HAMMING, crossCheck=True).match(db, da), key=lambda x: x.distance)[:400]
        pb = np.float32([kb[x.queryIdx].pt for x in m]); pa = np.float32([ka[x.trainIdx].pt for x in m])
        Mf, inl = cv2.estimateAffinePartial2D(pb, pa, method=cv2.RANSAC, ransacReprojThreshold=2)
        if Mf is None: continue
        # score: how well the furniture band of B lands on A
        wb = cv2.warpAffine(gb, Mf, (ga.shape[1], ga.shape[0])).astype(float)
        wm = cv2.warpAffine((mb > 128).astype(np.uint8), Mf, (ga.shape[1], ga.shape[0])) > 0
        band = np.zeros_like(wm); band[int(ga.shape[0] * (1 - frac * 0.7)):] = True
        both = band & wm & (ma > 128); onlyone = band & (wm ^ (ma > 128))
        if both.sum() < 500: continue
        err = np.abs(wb[both] - ga[both].astype(float)).mean() + 60 * onlyone.sum() / max(1, (band & ((ma > 128) | wm)).sum())
        if best is None or err < best[0]: best = (err, Mf, inl, f)
    if best is None: print(B, 'no fit'); continue
    err, M, inl, f = best
    k = float(np.hypot(M[0, 0], M[1, 0])); tx, ty = float(M[0, 2]), float(M[1, 2])
    if not 0.8 < k < 1.25: print(B, 'bad scale', k); continue
    a = meta[A]; b = meta[B]
    b['h'] = round(a['h'] / k, 2); b['ax'] = round((a['ax'] - tx) / k, 1); b['fy'] = round((a['fy'] - ty) / k, 1)
    print(B, 'k=%.3f t=(%.1f,%.1f) inliers=%d frac=%.2f err=%.1f' % (k, tx, ty, int(inl.sum()), f, err))
for n, f in SCALE.items():
    if n in meta and not meta[n].get('scaled'): meta[n]['h'] = round(meta[n]['h'] / f, 2); meta[n]['scaled'] = f
# two-person frames: anchor on the middle of the couple, so poses don't jump sideways
for n in ('pair_unbutton', 'pair_kiss', 'pair_brow'):
    if n in meta: meta[n]['ax'] = round(meta[n]['w'] / 2, 1)
for n, v in FACING.items():
    if n in meta:
        if v: meta[n]['facesLeft'] = True
        else: meta[n].pop('facesLeft', None)
with open(js, 'w') as fh:
    fh.write('// Generated by scripts/matte.py: painted sprite frames (size, head anchor, feet line).\nwindow.SPRITES = ' + json.dumps(dict(sorted(meta.items())), indent=1) + ';\n')
