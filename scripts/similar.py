# Near-identical frame pairs, for the engine's short cross-fade (js/similar.js).
#   python3 scripts/similar.py [THRESHOLD=0.85]
# Two frames of the same character count as similar when their silhouettes, drawn the way the engine
# draws them (same height, feet on the anchor), overlap by at least THRESHOLD (intersection / union).
# A swap between them (a mouth, a hand, a drag on the cigarette) then eases over 100 ms instead of
# cutting; very different poses are left to the morphs (js/morphs.js) or a clean cut.
import json, os, sys, itertools
import numpy as np
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TH = float(sys.argv[1]) if len(sys.argv) > 1 else 0.85
GROUPS = {'alan'}
H = 120  # mask height in px (a frame drawn at this character height)
txt = open(os.path.join(ROOT, 'js/sprites.js')).read(); META = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])


def mask(k):
    m = META[k]; s = H / m['h']
    im = Image.open(os.path.join(ROOT, f'art/sprites/{k}.webp')).convert('RGBA')
    im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.BILINEAR)
    a = np.asarray(im)[..., 3] > 128
    if m.get('facesLeft'): a = a[:, ::-1]; ax = (m['w'] - m['ax']) * s
    else: ax = m['ax'] * s
    c = np.zeros((2 * H, 3 * H), bool)  # canvas with the anchor at (1.5H, 1.6H)
    ox, oy = round(1.5 * H - ax), round(1.6 * H - m['fy'] * s)
    y0, x0 = max(0, oy), max(0, ox); y1, x1 = min(c.shape[0], oy + a.shape[0]), min(c.shape[1], ox + a.shape[1])
    if y1 > y0 and x1 > x0: c[y0:y1, x0:x1] = a[y0 - oy:y1 - oy, x0 - ox:x1 - ox]
    return c


def main():
    groups = {}
    for k in META:
        if not os.path.exists(os.path.join(ROOT, f'art/sprites/{k}.webp')): continue
        groups.setdefault(k.split('_')[0], []).append(k)
    out = {}
    for g, ks in groups.items():
        if g not in GROUPS: continue  # Alan for now (phase 2); other characters keep their clean cuts
        ms = {k: mask(k) for k in ks}
        for a, b in itertools.combinations(sorted(ks), 2):
            if ('back' in a.split('_')) != ('back' in b.split('_')): continue  # a back view and a front view can share an outline
            A, B = ms[a], ms[b]
            u = (A | B).sum()
            if u and (A & B).sum() / u >= TH: out[f'{a}|{b}'] = 1
    with open(os.path.join(ROOT, 'js/similar.js'), 'w') as fh:
        fh.write('// Generated by scripts/similar.py: near-identical frame pairs (the engine eases between them over 100 ms).\n'
                 'window.SIMILAR = ' + json.dumps(out, separators=(',', ':')) + ';\n')
    print(len(out), 'similar pairs')


if __name__ == '__main__':
    main()
