# Sets a frame's anchor (ax, fy) so its lower body / furniture sits exactly where the base
# frame's does: best alpha overlap of the bottom band, searched over x (and a little y).
#   python3 scripts/align_to_base.py base frame [frame...]   [BAND=0.35]
import sys, os, json, numpy as np
from PIL import Image
js = 'js/sprites.js'; txt = open(js).read(); meta = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
band = float(os.environ.get('BAND', 0.35))
def load(n):
    m = meta[n]; a = np.asarray(Image.open(f'art/sprites/{n}.webp').convert('RGBA'))[..., 3] > 128
    k = 720.0 / m['h']; return a, m, k  # all frames drawn at h -> 720 scale
base = sys.argv[1]; A, mb, kb = load(base)
# base band in "anchor space": coords relative to (ax, fy)
def pts(a, m, lo):
    ys, xs = np.where(a); sel = ys > m['fy'] - lo; return xs[sel] - m['ax'], ys[sel] - m['fy']
H = (mb['fy'] - mb['top']) * band
bx, by = pts(A, mb, H)
grid = np.zeros((int(H) + 40, 1600), bool); grid[(by + H + 20).astype(int).clip(0, grid.shape[0] - 1), (bx + 800).astype(int).clip(0, 1599)] = True
for n in sys.argv[2:]:
    a, m, k = load(n); fx, fyy = pts(a, m, H + 20)
    best = None
    for dy in range(-int(os.environ.get("DY", 12)), int(os.environ.get("DY", 12)) + 1, 2):
        for dx in range(-160, 161, 2):
            X = (fx + dx + 800).astype(int); Y = (fyy + dy + H + 20).astype(int)
            ok = (X >= 0) & (X < 1600) & (Y >= 0) & (Y < grid.shape[0])
            inter = grid[Y[ok], X[ok]].sum(); score = inter / (len(bx) + ok.sum() - inter)
            if best is None or score > best[0]: best = (score, dx, dy)
    s, dx, dy = best
    meta[n]['ax'] = round(m['ax'] - dx, 1); meta[n]['fy'] = round(m['fy'] - dy, 1)
    print(n, 'iou %.2f' % s, 'dx', dx, 'dy', dy, '->', meta[n]['ax'], meta[n]['fy'])
with open(js, 'w') as fh:
    fh.write('// Generated by scripts/matte.py: painted sprite frames (size, head anchor, feet line).\nwindow.SPRITES = ' + json.dumps(dict(sorted(meta.items())), indent=1) + ';\n')
