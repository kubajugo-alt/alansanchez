#!/usr/bin/env python3
"""The placement tool, step 3 (ported from Game II's sequel/scripts/extras_install.py, 2026-11-04): the user's placements
into the game, once the user says they're done.

  python3 scripts/placer_install.py <placements.json> [tool folder]      (default folder art/review/placer/)

placements.json is the tool's `placements` collection saved as {doc id: record}; a record that moved someone already
in a room is {cast: <person key>, room, x, y, size, flip, z}. Each becomes an entry of S.PLACED in js/story/placed.js
(js/story/layout.js writes it into the room before the game starts), worked out so the game shows them as the tool did:
  x, y      where their feet are
  dir       turned round (e <-> w) when flipped from how the game stood them; a background extra that never turns gets
            flip: true and the facing that mirrors it
  h / size  the height the tool showed (it follows the floor's depth, unclamped, times the slider): a person with a fixed
            height in the room gets a new h, anyone else a size (the game's depth scale is clamped to the floor's range)
  z         to front / to back (the depth order's nudge)
A person left where the game stood them writes nothing. Records for new background figures ({extra: ...}) are reported
and skipped: Game I has no background figures painted for the tool (Game II's scripts/extras.py and extras_install.py
make and install those; they need new art, which needs the user's approval first).
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if len(sys.argv) < 2: raise SystemExit(__doc__)
P = json.load(open(sys.argv[1]))
TOOL = os.path.abspath(sys.argv[2]) if len(sys.argv) > 2 else os.path.join(ROOT, 'art/review/placer')
D = json.load(open(os.path.join(TOOL, 'data.json')))
ROOMS = {r['id']: r for r in D['rooms']}
CAST = {(room, c['key']): c for room, cs in D['cast'].items() for c in cs}


def free(room, y):   # the tool's height at a depth (unclamped)
    y0, h0, y1, h1 = ROOMS[room]['scale']; return h0 + (h1 - h0) * (y - y0) / (y1 - y0)


def game(room, y):   # the game's (E.scaleAt: clamped to the floor's range)
    y0, h0, y1, h1 = ROOMS[room]['scale']; return h0 + (h1 - h0) * max(0, min(1, (y - y0) / (y1 - y0)))


def main():
    out, skipped = {}, []
    for doc, p in sorted(P.items(), key=lambda t: (t[1].get('room', ''), t[1].get('y', 0))):
        if 'cast' not in p: skipped.append(p.get('extra', doc)); continue
        room, c = p['room'], CAST.get((p['room'], p['cast']))
        if c is None: print('not in the tool any more:', room, p['cast']); continue
        g, size, flip, z = c['game'], p.get('size', 1) or 1, bool(p.get('flip')), p.get('z', 0) or 0
        if (p['x'], p['y']) == (c['x'], c['y']) and abs(size - 1) < 0.005 and flip == c['flip'] and not z: continue
        e = {'x': round(p['x']), 'y': round(p['y'])}
        if flip != c['flip']:
            if c['ambient'] and not c['flip']: e['flip'] = True; e['dir'] = 'e' if g['facesLeft'] else 'w'
            elif g['dir'] in ('e', 'w'): e['dir'] = {'e': 'w', 'w': 'e'}[g['dir']]
            else: e['dir'] = 'e' if flip == g['facesLeft'] else 'w'   # (a front or back view: the side that shows it so)
        ratio = free(room, p['y']) / free(room, c['y']) * size   # (the tool: its first height, carried by the depth, times the slider)
        if g['fixedH']: e['h'] = round(g['fixedH'] * ratio, 1)
        else:
            s = g['size'] * ratio * game(room, c['y']) / game(room, p['y'])
            if abs(s - g['size']) > 0.005: e['size'] = round(s, 3)
        if z: e['z'] = g['z'] + z
        out.setdefault(room, {})[c['key']] = e
    with open(os.environ.get('PLACED_OUT') or os.path.join(ROOT, 'js/story/placed.js'), 'w') as f:   # (PLACED_OUT: a trial elsewhere)
        f.write('// Generated by scripts/placer_install.py from the placement tool: where the user stood people in each room,\n'
                '// {room: {person key: {x, y, dir?, flip?, h?, size?, z?}}}; js/story/layout.js writes it into the rooms. Do not edit by hand.\n')
        f.write('window.S.PLACED = ' + json.dumps(out, indent=1, sort_keys=True) + ';\n')
    print(sum(len(v) for v in out.values()), 'people placed in', len(out), 'rooms -> js/story/placed.js')
    if skipped: print(len(skipped), 'new background figures skipped (none painted for Game I):', ', '.join(map(str, skipped)))


if __name__ == '__main__':
    main()
