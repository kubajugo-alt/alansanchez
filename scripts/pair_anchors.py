# Anchors for combined sprites (Alan with someone else), so neither of them jumps on the way in or out.
#   python3 scripts/pair_anchors.py            -> art/review/alan/phase3/pair_anchors.json (report)
#   python3 scripts/pair_anchors.py --apply    -> writes ax / fy / h / px / pfy into js/sprites.js
# For each pair frame, Alan's side of the picture (x range below) is measured on its own:
#   ax, fy  = the point between Alan's boots (the anchor the engine draws on, like his solo frames)
#   h       = his head-to-feet height when he's standing, so he's drawn the size of his solo frames
#   px, pfy = the point between the partner's feet: the scene stands the partner there before and after
# Pairs where Alan isn't standing (kneeling, seated, piggyback, hopping) or stoops well below his standing height
# (leaning in, bending: under 690 px) keep their scale, so the painting is never blown up to make him tall.
import json, os, sys
import numpy as np, cv2
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ALAN_SIDE = {'pair_brow': (.45, 1), 'pair_kiss': (.5, 1), 'pair_unbutton': (.5, 1),
             **{f'pair_cop_{k}': (.5, 1) for k in ['arm', 'belt', 'belt2', 'buttons', 'chest', 'shelf2', 'trousers', 'tshirt', 'cuffs']},
             **{f'pair_cop_{k}': (.45, 1) for k in ['jacket', 'neck', 'shelf']},
             **{f'pair_guitar_{k}': (.5, 1) for k in ['d1', 'd2', 'h1', 'h2', 'hop', 'j0', 'j1', 'j2', 'jackets', 'lasso', 's1', 's2',
                                                       'shirtfly', 'u1', 'u2', 'undress2', 'l1', 'l2', 'p1', 'underwear']},
             'pair_guitar_lesson': (.45, 1),
             **{f'pair_vasco_{k}': (0, .5) for k in ['card', 'catch', 'clapper', 'coffee', 'fragment', 'kiss', 'kneel', 'ladder',
                                                      'lanyard', 'shirtless', 'thumb']},
             **{f'pair_wring_{k}': (.55, 1) for k in '123'}}
NOT_STANDING = {'pair_vasco_kneel', 'pair_vasco_ladder', 'pair_guitar_p1', 'pair_guitar_l2', 'pair_guitar_underwear',
                'pair_guitar_hop', 'pair_guitar_h1', 'pair_guitar_h2', 'pair_guitar_d1', 'pair_guitar_d2', 'pair_guitar_l1',
                'pair_guitar_lasso', 'pair_cop_trousers', 'pair_cop_cuffs'}


def feet(al, x0, x1):
    """(feet_x, sole_y, head_y) of the figure inside columns x0..x1."""
    sub = np.zeros_like(al); sub[:, x0:x1] = al[:, x0:x1]
    ys, xs = np.where(sub)
    top, bot = ys.min(), ys.max(); H = bot - top
    band = np.zeros_like(sub); y0 = int(bot - H * 0.10); band[y0:] = sub[y0:]
    n, lab, st, cen = cv2.connectedComponentsWithStats(band.astype(np.uint8), 8)
    blobs = sorted(((st[i, cv2.CC_STAT_AREA], cen[i][0]) for i in range(1, n)), reverse=True)
    blobs = [b for b in blobs if b[0] >= blobs[0][0] * 0.25][:2]
    fx = blobs[0][1] if len(blobs) == 1 else (blobs[0][1] + blobs[1][1]) / 2
    return float(fx), float(bot), float(top)


def main():
    txt = open(os.path.join(ROOT, 'js/sprites.js')).read(); M = json.loads(txt[txt.index('{'):txt.rindex('}') + 1])
    out = {}
    for k, (a0, a1) in sorted(ALAN_SIDE.items()):
        if k not in M: continue
        al = np.asarray(Image.open(os.path.join(ROOT, f'art/sprites/{k}.webp')).convert('RGBA'))[..., 3] > 128
        W = al.shape[1]
        ax, fy, top = feet(al, int(a0 * W), int(a1 * W))
        p0, p1 = (int(a1 * W), W) if a0 == 0 else (0, int(a0 * W))
        px, pfy, ptop = feet(al, p0, p1)
        m = M[k]; r = dict(old_ax=m['ax'], old_fy=m['fy'], old_h=m['h'], ax=round(ax, 1), fy=round(fy + 0.5, 1), px=round(px, 1), pfy=round(pfy + 0.5, 1),
                           alan_height=round(fy - top), partner_height=round(pfy - ptop), standing=k not in NOT_STANDING)
        r['h'] = float(round(fy - top)) if r['standing'] and fy - top >= 690 else m['h']
        out[k] = r
    os.makedirs(os.path.join(ROOT, 'art/review/alan/phase3'), exist_ok=True)
    json.dump(out, open(os.path.join(ROOT, 'art/review/alan/phase3/pair_anchors.json'), 'w'), indent=1)
    if '--apply' in sys.argv:
        for k, r in out.items():
            M[k].update(ax=r['ax'], fy=r['fy'], h=r['h'], px=r['px'], pfy=r['pfy'], rigid=True)
        with open(os.path.join(ROOT, 'js/sprites.js'), 'w') as fh:
            fh.write('// Generated by scripts/matte.py: painted sprite frames (size, head anchor, feet line).\nwindow.SPRITES = '
                     + json.dumps(dict(sorted(M.items())), indent=1) + ';\n')
    for k, r in out.items(): print(f"{k:24} ax {r['old_ax']:6}->{r['ax']:6}  px {r['px']:6}  h {r['old_h']}->{r['h']}  alan {r['alan_height']} partner {r['partner_height']} {'' if r['standing'] else '(not standing)'}")


if __name__ == '__main__':
    main()
